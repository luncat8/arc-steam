'use strict';
// Regenerate js/element-cdf.js: the measured cumulative distribution of the
// element noise js/geology.js produces. The shape is a property of the noise
// algorithm, never of the seed, so it is measured once from a wide sample and
// baked. Run with `node experiments/element-cdf.cjs [--write]`; without
// `--write` it prints the statistics and stops.
const fs = require('node:fs');
const path = require('node:path');
const geology = require('../js/geology.js');

const nodes = 256;
const histogramBins = 8192;
const samples = 20e6;
const side = Math.round(Math.sqrt(samples));
const stepX = 0.0371;
const stepY = 0.0413;

const bins = new Float64Array(histogramBins);
let total = 0;
for (let i = 0; i < side; i++) {
	for (let j = 0; j < side; j++) {
		const value = geology.sampleNoise(1, i * stepX, j * stepY, 0);
		bins[Math.min(histogramBins - 1, Math.floor(value * histogramBins))]++;
		total++;
	}
}
const cumulative = new Float64Array(histogramBins);
let sum = 0;
for (let i = 0; i < histogramBins; i++) {
	sum += bins[i];
	cumulative[i] = sum / total;
}
const table = new Array(nodes + 1);
for (let i = 0; i <= nodes; i++) {
	const at = (i / nodes) * histogramBins - 0.5;
	const low = Math.max(0, Math.min(histogramBins - 1, Math.floor(at)));
	const high = Math.min(histogramBins - 1, low + 1);
	const t = Math.max(0, Math.min(1, at - low));
	table[i] = cumulative[low] + (cumulative[high] - cumulative[low]) * t;
}
table[0] = 0;
table[nodes] = 1;

// Check the remap on an independent sample: a uniform field has mean 0.5 and
// sd 0.2887.
let mean = 0;
let square = 0;
let counted = 0;
const deciles = new Float64Array(10);
for (let i = 0; i < 900; i++) {
	for (let j = 0; j < 900; j++) {
		const flat = geology.flatten(geology.sampleNoise(1, i * stepX, j * stepY, 0));
		mean += flat;
		square += flat * flat;
		deciles[Math.min(9, Math.floor(flat * 10))]++;
		counted++;
	}
}
mean /= counted;
const sd = Math.sqrt(square / counted - mean * mean);
console.log('samples          ' + total);
console.log('remapped mean    ' + mean.toFixed(5) + '  (uniform 0.5)');
console.log('remapped sd      ' + sd.toFixed(5) + '  (uniform 0.28868)');
console.log('decile shares %  ' + Array.from(deciles, value => (value / counted * 100).toFixed(2)).join(' '));

if (!process.argv.includes('--write')) {
	console.log('\nrun with --write to overwrite js/element-cdf.js');
	process.exit(0);
}
const rows = [];
for (let i = 0; i <= nodes; i += 8) rows.push('\t\t' + table.slice(i, i + 8).map(value => value.toFixed(6)).join(', ') + ',');
const source = `// Measured cumulative distribution of the value-noise field generated by
// js/geology.js: P(noise < value) on a 0..1 grid of 257 nodes. Applying it to a
// channel turns the raw bell-shaped noise (mean 0.5, sd 0.215) into a field
// whose values are spread evenly over 0..1, so a mineral range's width is what
// makes it rare and a band near 0 or 1 is reachable at all.
//
// Regenerate with \`node experiments/element-cdf.cjs\`; the shape depends on the
// noise algorithm, never on the seed. experiments/geology.test.js checks that
// the flattened field is uniform, which fails if this table goes stale.
(function (root) {
	'use strict';

	const elementCdf = Object.freeze([
${rows.join('\n')}
	]);
	root.SteamElementCdf = elementCdf;
	if (typeof module !== 'undefined' && module.exports) module.exports = elementCdf;
})(typeof globalThis !== 'undefined' ? globalThis : this);
`;
fs.writeFileSync(path.join(__dirname, '..', 'js', 'element-cdf.js'), source);
console.log('\nwrote js/element-cdf.js');
